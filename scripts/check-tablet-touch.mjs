// Gesture safety checks supplement (and do not replace) the browser review.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import {JSDOM} from 'jsdom';
import {transform} from 'esbuild';
const dom=new JSDOM('<main><div class="lock-board"><button id="door">C2</button></div><div class="map"><button>Map door</button></div></main>',{runScripts:'outside-only',pretendToBeVisual:true});
const w=dom.window,root=w.document.querySelector('main'),door=root.querySelector('#door');
w.eval(fs.readFileSync(new URL('../public/lock-controls.js',import.meta.url),'utf8'));
root.insertAdjacentHTML('afterbegin',w.StoreWellLockUI.zoomButtons());
const board=w.StoreWellLockUI.zoomBoard(root);
let opened=0;door.onclick=()=>opened++;
const touch=(type,points,target=door)=>{
  const e=new w.Event(type,{bubbles:true,cancelable:true});
  Object.defineProperty(e,'touches',{value:points.map(([clientX,clientY])=>({clientX,clientY}))});
  target.dispatchEvent(e);return e;
};
assert(!touch('touchstart',[[10,10]]).defaultPrevented,'One finger can start native scrolling');
assert(!touch('touchmove',[[10,80]]).defaultPrevented,'One-finger scrolling remains native');
assert(touch('touchstart',[[10,10],[110,10]]).defaultPrevented);
assert(board.active);
touch('touchmove',[[10,10],[160,10]]);
assert.equal(root.dataset.lockScale,'150','Spreading two fingers enlarges the locks');
touch('touchmove',[[10,10],[60,10]]);
assert.equal(root.dataset.lockScale,'65','Closing two fingers reduces density down to the readable minimum');
touch('touchend',[[10,10]]);assert(board.active,'Ignore remaining finger until the whole pinch ends');
touch('touchend',[]);assert(!board.active);
door.dispatchEvent(new w.MouseEvent('click',{bubbles:true,detail:1}));
assert.equal(opened,0,'Lifting after a pinch must not open or alter a lock');
door.dispatchEvent(new w.MouseEvent('click',{bubbles:true,detail:0}));
assert.equal(opened,1,'Keyboard activation still works');
root.querySelector('[data-lock-zoom=reset]').click();assert.equal(root.dataset.lockScale,'100');
root.querySelector('[data-lock-zoom=in]').click();assert.equal(root.dataset.lockScale,'120');
root.querySelector('[data-lock-zoom=out]').click();assert.equal(root.dataset.lockScale,'100');
let mapZoom=1;const map=root.querySelector('.map');
w.StoreWellLockUI.pinchZoom(map,{get:()=>mapZoom,set:z=>mapZoom=z});
touch('touchstart',[[0,0],[100,0]],map);touch('touchmove',[[0,0],[200,0]],map);
assert.equal(mapZoom,2);assert.equal(root.dataset.lockScale,'100','Map zoom cannot resize lock-board controls');
touch('touchcancel',[],map);
assert(!touch('touchstart',[[0,0],[0,0]],map).defaultPrevented,'Coincident points never divide by zero');
const wheel=new w.WheelEvent('wheel',{bubbles:true,cancelable:true,ctrlKey:true,deltaY:-50});
map.dispatchEvent(wheel);assert(wheel.defaultPrevented);assert(mapZoom>2,'Trackpad pinch uses the same map zoom');
await transform(fs.readFileSync(new URL('../public/tablet-case.css',import.meta.url),'utf8'),{loader:'css'});
dom.window.close();
console.log('PASS: native one-finger scrolling; board and map pinch; readable zoom bounds; no ghost lock activation; keyboard, reset and trackpad controls. Touch events are simulated, not device-tested.');
